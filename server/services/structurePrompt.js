export function buildSuggestStructurePrompt({
  panelCount,
  theme,
  episodeSummary,
  conceptContext = '',
  dateContextBlock = '',
  futureDateInstruction = '',
  stageFacilitiesBlock = '',
  temporalContext = '',
  characterBlock = '',
  year,
  month,
  day,
  conceptConfigForStructure = null
}) {
  const mainCharacterRule = conceptConfigForStructure?.main_character
    ? '- 【厳守】主役の黒ねこ（主役の猫）は1コマに1匹まで。同一コマに2匹登場させないこと。各コマの content では主役の黒猫を1匹のみ描写すること。\n'
    : '';

  const panelFlowBlock = panelCount === 4
    ? `
【4コマの展開（厳守）】
4コマの場合は「起・承・転・結」の流れを基本とすること。
- 1コマ目（起）: **必ず「白地に黒文字」または「黒地に白文字」のテキストのみコマにすること。** このコマには「日付（${year}年${month}月${day}日）」と「まんが導入部分の説明の一言（ひらがなで、このエピソードの導入となる短い説明文）」を記載すること。イラストは一切描かないこと。
- 2コマ目（承）: 話の展開・発展
- 3コマ目（転）: ひねり・転換
- 4コマ目（結）: 結末（オチや余韻のどちらでも可）
会話は4コマで完結する必要はなく、余韻を残して終わってもよい。最後のコマで「オチ」にしなくても、静かな余韻や続きが想像できる終わり方でもよい。
各コマの content は上記の役割に沿った内容にすること。
`
    : `
【1コマ目について（厳守）】
- 1コマ目は**必ず「白地に黒文字」または「黒地に白文字」のテキストのみコマにすること。**
- このコマには「日付（${year}年${month}月${day}日）」と「まんが導入部分の説明の一言（ひらがなで、このエピソードの導入となる短い説明文）」を記載すること。
- イラストは一切描かないこと。
`;

  return `
あなたは${panelCount}コマ漫画の構成を考えるAIです。
以下の「テーマ」と「エピソード概要」に基づき、各コマの内容を${panelCount}コマ分だけ提案してください。${conceptContext}
シリーズ設定に「構成の基本」「構成ルール」がある場合は、それに従って各コマの流れと描き方の指示を決めてください。

【マンガの基本設定・トーン】
- 人間の会話が客観的に見ると滑稽であったり、純粋で微笑ましいものである
- 猫やキャラクターたちが、その会話を聞いている、あるいはその日に起きた出来事をその場で直接見聞きしている。舞台は日本・海外どちらでもよい（海外舞台の場合は、その場で見聞きしている描写にすること）
- 各コマの状況やセリフには、人情味、情緒、いとおしさを感じさせる要素を盛り込むこと。読者がほっこりしたり、心が温かくなるような描写を心がけること。
- **【厳守】日本の漫画の読順：コマもセリフも必ず右から順に配置すること。** 横に並ぶコマは右＝先に読む・左＝後に読む。1コマ内の複数セリフも右＝先に読む・左＝後に読むの順で書くこと。

【トーンの参考（含めると尚よい）】
天才バカボンやチャップリンのスラップスティック、星新一・筒井康隆のショートショートのような世界観を参考にすること。不思議な未来感、現実の滑稽さの暗喩、シュールなギャグが含まれていると尚よい。大げさにせず、ほっこりした日常の土台の上に、さりげない違和感・ひねり・オチをのせる程度でよい。

【エピソードの連続性（厳守）】
全コマは同一のエピソードとしてつながること。テーマとエピソード概要が描く「一つの話」を、コマを追うごとに展開すること。
- 1コマ目から最終コマまで、時間・場所・登場する人々の流れが自然に続くこと。急に別の話や無関係な場面に切り替えないこと。
- 前のコマで起きたことや言ったことへの反応・受け答えが次のコマに続くこと。因果関係が読めるようにすること。

${dateContextBlock}${futureDateInstruction}${stageFacilitiesBlock}${temporalContext ? '上記の日付・時代の文脈を反映し、会話や状況がその時代らしくなるように各コマの content を書くこと。\n\n' : ''}テーマ: ${theme || '（未入力）'}
エピソード概要: ${episodeSummary || '（未入力）'}${characterBlock}

【厳守】登場する人間（大人や子供たち）は、登録済みキャラクターの名前を呼ばないこと。人間とキャラクター（動物や神さま、精霊など）は別の次元で暮らしているため。子どもとキャラクターたちは近い領域に存在するが、言葉を交わし合うことはない。構成・セリフの中でもこの関係を守ること。
${mainCharacterRule}

【人間の描写について（最重要）】
- 人間の風貌や風景など、猫とキャラクター以外はほぼ登場させないこと
- 人間の子供や大人の会話は吹き出しとセリフのみで表現すること
- 必要に応じて人間がシルエットで登場することがあってもOK
- **人間のシルエットは、3D CG風の立体感をつけず、ただ暗いぼんやりした、輪郭のないシルエットで描くこと。リアルなシルエットや詳細な輪郭、3D CG風の立体感やライティングは避け、平面的でぼやけた暗い影のようなシルエットにすること**
- シーン説明では、人間の詳細な風貌や服装、風景の詳細な描写は避け、猫やキャラクターが中心となるようにすること

${panelFlowBlock}

【重要】各コマの content は以下の厳密型テンプレートで必ず記述すること:

**1コマ目について（厳守）**
- 1コマ目は必ず「〈構図：白地に黒字で文字だけ〉」または「〈構図：黒地に白字で文字だけ〉」のいずれかで記載すること。
- シーン説明には「${year}年${month}月${day}日」と、このエピソードの導入となる短い説明文（ひらがなで、10〜30文字程度）を記載すること。
- 例: 〈構図：白地に黒字で文字だけ〉\n${year}年${month}月${day}日。ある日のできごと。
- セリフは記載しないこと（1コマ目はテキストのみ）。

**2コマ目以降について**
1. 〈構図：構図の説明〉
   - カメラアングル、構図の種類（アップ、ロング、ワイドなど）を簡潔に
   - 文字だけのコマの場合は「〈構図：黒地に白字で文字だけ〉」または「〈構図：白地に黒字で文字だけ〉」と記載
   - 猫と吹き出しだけのコマの場合は「〈構図：背景なし。猫のイラストと吹き出しだけ〉」と記載
2. 人物配置：
   - 登場する人物・猫・キャラクターを**右から左の順**で記載すること
   - 2人なら「右＝...」「左＝...」、3人なら「右＝...」「中央＝...」「左＝...」の形式にすること
   - 話者がいる場合は、後述のセリフ欄の位置指定と必ず一致させること
3. 向き：
   - 各人物・猫・キャラクターがどちらを向いているかを個別に書くこと
   - 例: 「子供は左を向く」「おとなは右を向く」
4. 動作：
   - 誰が何をしているかを個別に簡潔に書くこと
   - 例: 「子供は焼け跡で見つけた茶碗を持っている」
5. セリフ：
   - セリフがある場合のみ記載。かっこ（）は使わないこと
   - **【厳守】位置と話者をセットで書くこと。** 例: 「右の子供【子供：おちゃわんが ひとつ あったよ】」
   - **【厳守】複数セリフがある場合は、必ず右→中央→左の順で並べること。**
   - 【厳守】セリフは漢字を使わず、ひらがな・カタカナ・アルファベット・数字で表記すること
   - 【厳守・セリフ長制約】1つのセリフは20文字以内にすること。1コマ内のセリフを合計しても40文字以内にすること
   - セリフがないコマは、この項目を省略すること

【構成内容（content）の注意】
- content の文章の中に、コマの縦横比を表すフレーズ（「アスペクト：landscape」など）は書かないこと。比率は別項目 aspect で指定するので、content には含めないこと。
- **人物配置・向き・動作・セリフの見出し名は必ずそのまま使うこと。** 別の見出し名に言い換えないこと。

【コマの種類】
- 1コマ目は必ずテキストのみコマ（白地に黒文字または黒地に白文字）にすること。
- 2コマ目以降でも、必要に応じて、第3者視点で「状況を説明する文字だけのコマ」を挿入してよい。その場合は content に説明文を記載し、aspect を指定すること（例: ナレーションや地の文のみのコマ）。全体の流れをわかりやすくするために、途中に文字だけのコマを挿入することも推奨する。

出力は JSON のみとし、以下の形式にしてください（panels は必ず ${panelCount} 個）:
{
  "panels": [
    {"panel": 1, "content": "〈構図：白地に黒字で文字だけ〉\n${year}年${month}月${day}日。ある日のできごと。", "aspect": "square"},
    {"panel": 2, "content": "〈構図：ロングショット〉\n人物配置：\n右＝子供\n左＝おとな\n向き：\n子供は左を向く\nおとなは右を向く\n動作：\n子供は焼け跡で見つけた茶碗を持っている\nおとなは子供を見る\nセリフ：\n右の子供【子供：おちゃわんが ひとつ あったよ】\n左のおとな【おとな：ああ よかったよ】", "aspect": "square"},
    {"panel": 3, "content": "〈構図：アップショット〉\n人物配置：\n右＝おとな\n左＝子供\n向き：\nおとなは左を向く\n子供は右を向く\n動作：\nおとなは茶碗を受け取りながらほっとしている\n子供はおとなを見上げる\nセリフ：\n右のおとな【おとな：ああ よかったよ】", "aspect": "square"},
    {"panel": 4, "content": "〈構図：ワイドショット〉\n人物配置：\n右＝子供\n左＝おとな\n向き：\n子供は左を向く\nおとなは右を向く\n動作：\nふたりが焼け跡の前で少し安心した空気になる", "aspect": "square"}
  ]
}

aspect は "landscape"（横長）, "square"（正方形）, "portrait"（縦長）のいずれか。縦横比は aspect で指定するため、content には書かないこと。
`;
}
